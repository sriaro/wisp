fn map() -> &'static HashMap<&'static str, &'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| TABLE.iter().copied().collect())
}

static LANG_NOW: AtomicU8 = AtomicU8::new(0);

pub fn zh() -> bool {
    match LANG_NOW.load(Ordering::Relaxed) {
        1 => false,
        2 => true,
        _ => {
            let now = match crate::engine::settings::lang_choice() {
                _ if std::env::var("WISP_LANG").is_ok_and(|v| v == "zh") => true,
                1 => false,
                2 => true,
                _ => crate::fonts::locale().starts_with("zh"),
            };
            LANG_NOW.store(if now { 2 } else { 1 }, Ordering::Relaxed);
            now
        }
    }
}

pub fn set_zh(now: bool) {
    LANG_NOW.store(if now { 2 } else { 1 }, Ordering::Relaxed);
}

fn zh_map() -> &'static HashMap<&'static str, &'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| crate::i18n_zh::TABLE.iter().copied().collect())
}

pub fn get(key: &str) -> String {
    if zh()
        && let Some(text) = zh_map().get(key) {
            return text.to_string();
        }
    map().get(key).map_or_else(|| key.to_string(), |text| text.to_string())
}

pub fn fmt(key: &str, args: &[&str]) -> String {
    let mut text = get(key);
    for (i, a) in args.iter().enumerate() {
        text = text.replace(&format!("{{{}}}", i), a);
    }
    text
}

